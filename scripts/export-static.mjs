#!/usr/bin/env node
/**
 * Builds the static mirror that GitHub Pages serves.
 *
 * Pages can only serve files, so this bakes the live server's API responses
 * into JSON and copies the client in beside them. The client notices
 * `window.__RADAR_STATIC__` and reads those files instead of a live API.
 *
 * Only the brief needs a language model, and a CI runner has none — so the
 * brief is carried over from the last local curation in `snapshot/brief.json`,
 * while everything else (items, strip, stats, source health) is rebuilt from
 * whatever was collected in this run.
 *
 *   node scripts/export-static.mjs              # build ./dist
 *   node scripts/export-static.mjs --snapshot   # refresh snapshot/brief.json from the local DB
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { ROOT, loadConfig } from "../server/config.js"
import { latestBrief, latestScan, queryItems, sourceHealth, stats, timeline } from "../server/db.js"

const DIST = join(ROOT, "dist")
const PUBLIC_DIR = join(ROOT, "public")
const SNAPSHOT = join(ROOT, "snapshot", "brief.json")

function writeFile(file, contents) {
  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, contents)
}

function writeJson(file, value) {
  writeFile(file, JSON.stringify(value))
}

function readSnapshot() {
  if (!existsSync(SNAPSHOT)) return null
  try {
    return JSON.parse(readFileSync(SNAPSHOT, "utf8"))
  } catch (err) {
    console.warn(`snapshot/brief.json is unreadable (${err.message}); ignoring it.`)
    return null
  }
}

/* --- --snapshot: capture the local brief for CI to reuse ------------------ */

if (process.argv.includes("--snapshot")) {
  const brief = latestBrief()
  if (!brief || brief.status !== "ok") {
    console.error(
      "No successful brief in the local database yet.\n" +
        "Start the radar with `npm start`, wait for a scan to finish, then run this again.",
    )
    process.exit(1)
  }
  writeJson(SNAPSHOT, brief)
  const sections = (brief.payload?.sections ?? []).length
  console.log(
    `snapshot/brief.json ← ${new Date(brief.createdAt).toISOString()} · ` +
      `${brief.itemCount} items in ${sections} sections · model ${brief.model}`,
  )
  process.exit(0)
}

/* --- build --------------------------------------------------------------- */

const config = loadConfig()
const dbBrief = latestBrief()

// Prefer a real brief from this database; fall back to the committed snapshot.
// A failed curation in the DB should not beat a good snapshot.
const brief = dbBrief?.status === "ok" ? dbBrief : (readSnapshot() ?? dbBrief)
const briefOrigin = dbBrief?.status === "ok" ? "database" : brief ? "snapshot" : "none"

const bootstrap = {
  brief,
  timeline: timeline(24, 48),
  stats: stats(),
  scan: { scanning: false, current: null, last: latestScan() },
  sources: sourceHealth(),
  sourceCount: config.sources.length,
  refreshMinutes: config.refreshMinutes,
  model: config.model,
  topics: config.topics.map(({ id, name, color }) => ({ id, name, color })),
  serverTime: Date.now(),
}

// The mirror has no way to persist read/saved state, so it ships without any:
// a public page should not render half its list greyed out.
const items = queryItems({ hours: 48, limit: 2000 }).map((item) => ({ ...item, read: false, saved: false }))

const briefItems = []
if (brief?.payload?.lead?.item) briefItems.push(brief.payload.lead.item)
for (const section of brief?.payload?.sections ?? []) {
  for (const entry of section.entries ?? []) if (entry.item) briefItems.push(entry.item)
}

rmSync(DIST, { recursive: true, force: true })
mkdirSync(DIST, { recursive: true })

copyFileSync(join(PUBLIC_DIR, "styles.css"), join(DIST, "styles.css"))
copyFileSync(join(PUBLIC_DIR, "app.js"), join(DIST, "app.js"))

// The server serves /styles.css and /app.js from the domain root. A Pages
// project site lives under /repo-name/, so those need to become relative.
const html = readFileSync(join(PUBLIC_DIR, "index.html"), "utf8")
  .replace('href="/styles.css"', 'href="./styles.css"')
  .replace(
    '<script type="module" src="/app.js"></script>',
    '<script src="./static-config.js"></script>\n    <script type="module" src="./app.js"></script>',
  )
writeFile(join(DIST, "index.html"), html)

writeFile(
  join(DIST, "static-config.js"),
  [
    "/* Generated by scripts/export-static.mjs — switches the client into read-only mirror mode. */",
    "window.__RADAR_STATIC__ = true",
    'window.__RADAR_API_BASE__ = "./api"',
    `window.__RADAR_BUILT_AT__ = ${Date.now()}`,
    "",
  ].join("\n"),
)

writeJson(join(DIST, "api", "bootstrap.json"), bootstrap)
writeJson(join(DIST, "api", "items.json"), { items })
if (brief?.id) writeJson(join(DIST, "api", "briefs", `${brief.id}.json`), { brief, items: briefItems })

// Carry the explainer across if it exists, so the public site documents itself.
if (existsSync(join(ROOT, "how-it-works.html"))) {
  copyFileSync(join(ROOT, "how-it-works.html"), join(DIST, "how-it-works.html"))
}

// Stop GitHub Pages from running Jekyll over the output.
writeFile(join(DIST, ".nojekyll"), "")

const kb = (n) => `${Math.round(n / 1024)} KB`
console.log(`dist/ built — ${items.length} items, ${bootstrap.timeline.slots.length} strip slots`)
console.log(`  brief   : ${briefOrigin}${brief?.id ? ` (${brief.id})` : ""}`)
console.log(`  sources : ${bootstrap.sources.length} reporting of ${config.sources.length}`)
console.log(`  size    : ${kb(JSON.stringify(bootstrap).length + JSON.stringify(items).length)} of JSON`)
